'use client';
import { useState } from 'react';
import { useRouter } from 'next/navigation';
import type { Alert, HealthMemory, Recommendation } from '@bho/contracts';
import { Chip } from './ui';

const statusTone = (s: string): 'good' | 'watch' | 'attention' | 'neutral' => (s === 'COMPLETED' ? 'good' : s === 'DISCUSS_WITH_CLINICIAN' ? 'watch' : s === 'NEW' ? 'attention' : 'neutral');
const claimTone = (c: string): 'good' | 'watch' | 'attention' | 'neutral' => (c === 'MEASURED_FACT' ? 'good' : c === 'HYPOTHESIS' ? 'watch' : c === 'RECOMMENDATION' ? 'attention' : 'neutral');
const btn = 'rounded-lg border border-line px-2 py-1 text-xs text-muted hover:text-ink disabled:opacity-50';

export function RecommendationCard({ rec }: { rec: Recommendation }) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const [reason, setReason] = useState('');
  const [snooze, setSnooze] = useState('');
  const [msg, setMsg] = useState<string | null>(null);
  async function update(status: Recommendation['status']) {
    setBusy(true);
    setMsg(null);
    const payload: Record<string, unknown> = { status };
    if (status === 'SNOOZED') payload.snoozedUntil = snooze;
    if (status === 'DISMISSED') payload.dismissReason = reason || undefined;
    const res = await fetch(`/api/proxy/v1/recommendations/${rec.id}`, { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify(payload) });
    setBusy(false);
    if (!res.ok) setMsg((await res.json()).message ?? 'update failed');
    router.refresh();
  }
  const active = ['NEW', 'ACCEPTED', 'IN_PROGRESS', 'DISCUSS_WITH_CLINICIAN', 'SNOOZED'].includes(rec.status);
  return (
    <li id={`rec-${rec.id}`} className="rounded-xl border border-line p-3" data-testid="rec-card" data-status={rec.status}>
      <div className="flex flex-wrap items-center gap-2">
        {rec.priority && <span className="rounded-full bg-accent px-2 text-xs font-semibold text-white dark:text-black">P{rec.priority}</span>}
        <span className="font-medium">{rec.title}</span>
        <Chip tone={claimTone(rec.claimType)}>{rec.claimType.replace(/_/g, ' ').toLowerCase()}</Chip>
        <Chip tone={statusTone(rec.status)}>{rec.status.replace(/_/g, ' ').toLowerCase()}</Chip>
        <Chip tone="neutral">{rec.confidence.toLowerCase()} confidence</Chip>
        {rec.clinicianReviewStatus !== 'NOT_REQUIRED' && <Chip tone="watch">clinician review {rec.clinicianReviewStatus.toLowerCase()}</Chip>}
      </div>
      <p className="mt-2 text-sm"><span className="text-muted">Observation: </span>{rec.observation}</p>
      {rec.interpretation && <p className="mt-1 text-sm"><span className="text-muted">Interpretation: </span>{rec.interpretation}</p>}
      <p className="mt-1 text-sm"><span className="text-muted">Proposed action: </span>{rec.proposedAction}</p>
      <p className="mt-1 text-xs text-muted">{rec.reason}{rec.expectedBenefit ? ` · Expected: ${rec.expectedBenefit}` : ''}{rec.requiredEffort ? ` · Effort: ${rec.requiredEffort.toLowerCase()}` : ''}{rec.estimatedCost ? ` · Cost: ${rec.estimatedCost}` : ''}</p>
      {rec.limitations && <p className="mt-1 text-[11px] text-muted">Limitations: {rec.limitations}</p>}
      {rec.outcome && <p className="mt-1 text-xs"><span className="text-muted">Outcome (descriptive, not causal): </span>{String((rec.outcome as { summary?: string }).summary ?? '')}</p>}
      <button onClick={() => setOpen(!open)} className="mt-2 text-xs text-accent" data-testid="rec-evidence-toggle">{open ? 'Hide' : 'Show'} evidence ({rec.evidence.length})</button>
      {open && (
        <ul className="mt-2 space-y-1 rounded-lg bg-surface-2 p-2 text-xs" data-testid="rec-evidence">
          {rec.evidence.map((e) => (
            <li key={e.id}><span className="uppercase tracking-wide text-muted">{e.evidenceType.replace(/_/g, ' ')}</span> · {e.citation}{e.strength ? ` · ${e.strength}` : ''}{e.applicability ? ` · ${e.applicability}` : ''}{e.limitations ? ` · ${e.limitations}` : ''}{e.lastVerifiedAt ? ` · verified ${e.lastVerifiedAt.slice(0, 10)}` : e.evidenceType === 'GUIDELINE' || e.evidenceType === 'STUDY' ? ' · citation not yet verified by a clinician' : ''}</li>
          ))}
          <li className="text-muted">Packet items: {rec.packetItemIds.join(', ') || '—'} · generated by {rec.generatedBy}{rec.expiresAt ? ` · expires ${rec.expiresAt.slice(0, 10)}` : ''}</li>
        </ul>
      )}
      {active && (
        <div className="mt-3 flex flex-wrap items-center gap-2">
          {rec.status !== 'ACCEPTED' && rec.status !== 'IN_PROGRESS' && <button disabled={busy} onClick={() => update('ACCEPTED')} className={btn} data-testid="rec-accept">Accept</button>}
          {rec.status === 'ACCEPTED' && <button disabled={busy} onClick={() => update('IN_PROGRESS')} className={btn}>In progress</button>}
          {(rec.status === 'ACCEPTED' || rec.status === 'IN_PROGRESS') && <button disabled={busy} onClick={() => update('COMPLETED')} className={btn}>Completed</button>}
          {rec.status !== 'DISCUSS_WITH_CLINICIAN' && <button disabled={busy} onClick={() => update('DISCUSS_WITH_CLINICIAN')} className={btn}>Discuss with clinician</button>}
          <span className="flex items-center gap-1"><input type="date" value={snooze} onChange={(e) => setSnooze(e.target.value)} className="rounded-lg border border-line bg-surface-2 px-2 py-1 text-xs" aria-label="Snooze until" /><button disabled={busy || !snooze} onClick={() => update('SNOOZED')} className={btn}>Snooze</button></span>
          <span className="flex items-center gap-1"><input value={reason} onChange={(e) => setReason(e.target.value)} placeholder="Why dismiss? (optional)" className="rounded-lg border border-line bg-surface-2 px-2 py-1 text-xs" /><button disabled={busy} onClick={() => update('DISMISSED')} className={`${btn} border-attention/40 text-attention`} data-testid="rec-dismiss">Dismiss</button></span>
          {msg && <span className="text-xs text-attention">{msg}</span>}
        </div>
      )}
    </li>
  );
}

export function AlertRow({ alert }: { alert: Alert }) {
  const router = useRouter();
  async function act(action: 'read' | 'dismissed') {
    await fetch(`/api/proxy/v1/alerts/${alert.id}`, { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action }) });
    router.refresh();
  }
  const unread = !alert.readAt && !alert.dismissedAt;
  return (
    <li className={`flex flex-wrap items-start justify-between gap-2 py-2 ${unread ? '' : 'opacity-60'}`} data-testid="alert-row">
      <div>
        <p className="text-sm font-medium">{alert.title} <Chip tone={alert.severity === 'URGENT' ? 'attention' : alert.severity === 'ATTENTION' ? 'watch' : 'neutral'}>{alert.severity.toLowerCase()}</Chip></p>
        {alert.body && <p className="text-xs text-muted">{alert.body}</p>}
        <p className="text-[11px] text-muted">{new Date(alert.createdAt).toLocaleString()} · {alert.kind.replace(/_/g, ' ').toLowerCase()}</p>
      </div>
      {unread && <span className="flex gap-1"><button onClick={() => act('read')} className={btn} data-testid="alert-read">Mark read</button><button onClick={() => act('dismissed')} className={btn}>Dismiss</button></span>}
    </li>
  );
}

const CATEGORIES = ['GOAL', 'BASELINE', 'INTERVENTION', 'DIAGNOSIS', 'MEDICATION', 'ALLERGY', 'FAMILY_HISTORY', 'PREFERENCE', 'CLINICAL_EVENT', 'RECOMMENDATION', 'EXPERIMENT', 'CLINICIAN_INSTRUCTION', 'PRIORITY'];
export function MemoryPanel({ memories }: { memories: HealthMemory[] }) {
  const router = useRouter();
  const [statement, setStatement] = useState('');
  const [category, setCategory] = useState('PREFERENCE');
  const [origin, setOrigin] = useState('USER_REPORTED');
  const input = 'rounded-lg border border-line bg-surface-2 px-2 py-1 text-xs';
  async function add(e: React.FormEvent) {
    e.preventDefault();
    await fetch('/api/proxy/v1/memories', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ statement, category, origin, confidence: origin === 'CLINICIAN_DOCUMENTED' ? 'HIGH' : 'MEDIUM' }) });
    setStatement('');
    router.refresh();
  }
  async function patch(id: string, body: Record<string, unknown>) {
    await fetch(`/api/proxy/v1/memories/${id}`, { method: 'PATCH', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
    router.refresh();
  }
  async function remove(id: string) {
    if (!confirm('Delete this memory? It is removed, not archived.')) return;
    await fetch(`/api/proxy/v1/memories/${id}`, { method: 'DELETE' });
    router.refresh();
  }
  return (
    <div>
      <ul className="divide-y divide-line text-sm" data-testid="memory-list">
        {memories.map((m) => (
          <li key={m.id} className="flex flex-wrap items-start justify-between gap-2 py-2">
            <div>
              <p>{m.statement}</p>
              <p className="text-[11px] text-muted">{m.category.toLowerCase().replace(/_/g, ' ')} · {m.origin.toLowerCase().replace(/_/g, ' ')} · <Chip tone={m.verificationStatus === 'UNVERIFIED' ? 'watch' : m.verificationStatus.endsWith('CONFIRMED') ? 'good' : 'neutral'}>{m.verificationStatus.toLowerCase().replace(/_/g, ' ')}</Chip> · {m.confidence.toLowerCase()} confidence · {m.recordedAt.slice(0, 10)}{m.sourceRef ? ` · ${m.sourceRef}` : ''}</p>
            </div>
            <span className="flex gap-1">
              {m.verificationStatus === 'UNVERIFIED' && <button onClick={() => patch(m.id, { verificationStatus: 'USER_CONFIRMED' })} className={btn}>Confirm</button>}
              <button onClick={() => patch(m.id, { verificationStatus: 'ARCHIVED' })} className={btn}>Archive</button>
              <button onClick={() => remove(m.id)} className={`${btn} border-attention/40 text-attention`}>Delete</button>
            </span>
          </li>
        ))}
        {memories.length === 0 && <li className="py-2 text-xs text-muted">Nothing remembered yet.</li>}
      </ul>
      <form onSubmit={add} className="mt-3 flex flex-wrap items-center gap-2">
        <input value={statement} onChange={(e) => setStatement(e.target.value)} placeholder="Something worth remembering (e.g. a clinician instruction)" className={`${input} min-w-64 flex-1`} data-testid="memory-statement" />
        <select value={category} onChange={(e) => setCategory(e.target.value)} className={input}>{CATEGORIES.map((c) => <option key={c} value={c}>{c.toLowerCase().replace(/_/g, ' ')}</option>)}</select>
        <select value={origin} onChange={(e) => setOrigin(e.target.value)} className={input}><option value="USER_REPORTED">user reported</option><option value="CLINICIAN_DOCUMENTED">clinician documented</option></select>
        <button disabled={!statement.trim()} className="rounded-lg bg-accent px-3 py-1 text-xs font-medium text-white disabled:opacity-50 dark:text-black" data-testid="memory-save">Remember</button>
      </form>
    </div>
  );
}
